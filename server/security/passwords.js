import * as argon2 from "argon2";
import { randomBytes, scrypt, timingSafeEqual } from "node:crypto";
import { promisify } from "node:util";
import { HttpError, readNewPassword } from "./input.js";

// Keep the old algorithm available fro existing password records.
const deriveLegacy = promisify(scrypt);

// Settings for New Password hashes.
// memoryCost is measure in KiB: 19456 KiB = 19 Mib.
const ARGON_OPTIONS = {
  type: argon2.argon2id,
  memoryCost: 19456,
  timeCost: 2,
  parallelism: 1,
  hashLength: 32,
};

// REV-SEC-02 (added 2026-10-26): every Argon2id cost setting this app has
// ever used. Verification accepts any of them, so raising the costs later
// does not lock existing users out. The FIRST entry must always match
// ARGON_OPTIONS above. Older entries are upgraded automatically the next
// time that user signs in (see needsRehash below).
const SUPPORTED_ARGON_PARAMETERS = [
  { m: 19456, t: 2, p: 1 }, // current: OWASP's minimum recommended Argon2id setting
];

function readArgonParameters(encoded) {
  if (typeof encoded !== "string" || encoded.length > 200) {
    return null;
  }

  // The three cost parameters may appear in different orders.
  const match =
    /^\$argon2id\$v=19\$((?:[mtp]=[0-9]{1,6},){2}[mtp]=[0-9]{1,6})\$[A-Za-z0-9+/]{22}\$[A-Za-z0-9+/]{43}$/.exec(
      encoded,
    );

  if (!match) {
    return null;
  }

  // Check that the three parameters are exactly m, t, and p, with no duplicates.
  const parameters = Object.fromEntries(
    match[1].split(",").map((pair) => {
      const [name, value] = pair.split("=");
      return [name, Number(value)];
    }),
  );
  return Object.keys(parameters).length === 3 ? parameters : null;
}

// Accept this application's intended Argon2id format and costs.
// Do not let a malformed stored has request unlimited memory or work.
function isSupportedArgonHash(encoded) {
  const parameters = readArgonParameters(encoded);
  return Boolean(
    parameters &&
      SUPPORTED_ARGON_PARAMETERS.some(
        ({ m, t, p }) => parameters.m === m && parameters.t === t && parameters.p === p,
      ),
  );
}

// legacy format for the older rev code
// REV-SEC-01: this line was missing "const". ES modules always run in strict
// mode, so the bare assignment threw "LEGACY_FORMAT is not defined" the moment
// this file loaded, and the whole server (and every auth test) failed to start.
const LEGACY_FORMAT = /^\$scrypt\$131072\$8\$1\$([a-f0-9]{32})\$([a-f0-9]{128})$/;

// Exact format previously generated by REV's scrypt helper.
const LEGACY_OPTIONS = {
  N: 131072,
  r: 8,
  p: 1,
  maxmem: 256 * 1024 * 1024, // 256 MiB
};

// REV-SEC-03 (added 2026-10-26): a small waiting line ("queue") for password work.
//
// Before: if more than 2 sign-ins arrived at the same moment, the extra ones
// failed immediately with 503 "busy". In testing, 4 of 8 simultaneous correct
// logins were refused, so an ordinary traffic spike locked real users out.
//
// Now: up to 4 hashes run at once (Node runs Argon2 on its 4 background
// worker threads by default), up to 32 more requests wait in line, and a
// request that waits longer than 10 seconds gets the 503. Memory stays
// bounded: 4 x 19 MiB = about 76 MiB at the very worst.
const MAX_CONCURRENT_HASHES = 4;
const MAX_WAITING_HASHES = 32;
const HASH_WAIT_TIMEOUT_MS = 10_000;

let active = 0;
const waiting = [];
let dummyHashPromise;

function busy() {
  return new HttpError(503, "Authentication is temporarily busy. Please try again.");
}

// Wait for a free hashing slot (or fail if the line is too long or too slow).
function acquireSlot() {
  if (active < MAX_CONCURRENT_HASHES) {
    active += 1;
    return Promise.resolve();
  }
  if (waiting.length >= MAX_WAITING_HASHES) {
    return Promise.reject(busy());
  }
  return new Promise((resolve, reject) => {
    const entry = { resolve, timer: null };
    entry.timer = setTimeout(() => {
      const index = waiting.indexOf(entry);
      if (index !== -1) waiting.splice(index, 1);
      reject(busy());
    }, HASH_WAIT_TIMEOUT_MS);
    entry.timer.unref?.();
    waiting.push(entry);
  });
}

// Hand the slot straight to the next waiting request, or free it.
function releaseSlot() {
  const next = waiting.shift();
  if (next) {
    clearTimeout(next.timer);
    next.resolve(); // the slot passes to the next request; "active" is unchanged
  } else {
    active -= 1;
  }
}

// Bound expensive password in this Node process.
// Request rate limits are a separate layer of protection.

async function withPasswordSlot(work) {
  await acquireSlot();

  // try /finally ensures the slot is released even if the work throws an error,
  // preventing the system from getting stuck in a busy state.
  try {
    return await work();
  } finally {
    // Release the slot even if hashing throws an error.
    releaseSlot();
  }
}

// REV-SEC-03: legacy scrypt needs 128 MiB per check, so only ONE may run at a
// time. Without this, a few simultaneous logins to an old account could use
// 512 MiB, the entire memory of a small hosting plan.
let legacyChain = Promise.resolve();
function withLegacySlot(work) {
  const run = legacyChain.then(work, work);
  legacyChain = run.catch(() => {});
  return run;
}

// Create a dummy hash for unknown accounts to prevent timing attacks.
function getDummyHash() {
  // An unknown account still performs password-verification work.
  // Create this process-local dummy has only when first needed.
  if (!dummyHashPromise) {
    dummyHashPromise = argon2
      .hash(randomBytes(32).toString("hex"), ARGON_OPTIONS)
      .catch((error) => {
        // Allow a later attempt to retry after a library failure.
        dummyHashPromise = undefined;
        throw error;
      });
  }
  return dummyHashPromise;
}

// Used when registering or choosing a NEW password.
// This is the only place where the new Argon2id algorithm is used.

export async function hashNewPassword(password) {
  readNewPassword(password);

  // Argon2 generates the random salt for us.
  return withPasswordSlot(() => argon2.hash(password, ARGON_OPTIONS));
}

// Used when checking an EXISTING password.
export async function verifyPassword(password, encoded) {
  // REV-SEC-02: refuse non-text passwords (the old scrypt version checked
  // this; the rewrite had dropped it). parseLogin() already guarantees text,
  // so this only protects against future programming mistakes.
  if (typeof password !== "string" || password.length < 1 || password.length > 128) {
    return false;
  }

  // REV-SEC-02 (timing fix): this function used to return false IMMEDIATELY
  // when `encoded` was missing, which is exactly what happens for an email
  // with no account. Unknown emails therefore answered about 8x faster
  // (2.8 ms vs 24 ms in testing), so a bot could find out which emails are
  // registered just by timing the login response. Now a missing or
  // unsupported hash falls through to the dummy-hash check below, so known
  // and unknown emails do the same amount of work.
  return withPasswordSlot(async () => {
    // current format.
    if (isSupportedArgonHash(encoded)) {
      return argon2.verify(encoded, password);
    }

    // Existing scrypt accounts remain able to sign in.
    const legacy =
      typeof encoded === "string" ? LEGACY_FORMAT.exec(encoded) : null;

    // If the legacy format is not matched, return false to indicate that the password verification failed.
    if (legacy) {
      const derived = await withLegacySlot(() =>
        deriveLegacy(password, legacy[1], 64, LEGACY_OPTIONS),
      );

      const expected = Buffer.from(legacy[2], "hex");

      return timingSafeEqual(derived, expected);
    }

    // Missing account or unsupported stored format:
    // do verification work, but NEVER accept the password.

    const dummyHash = await getDummyHash();

    // verify the dummy hash and password
    await argon2.verify(dummyHash, password);

    return false;
  });
}

// REV-SEC-02 (added 2026-10-26): true when a stored hash uses an older format
// (legacy scrypt, or older Argon2 costs). After a SUCCESSFUL sign-in the
// login service re-hashes the password with the current settings, so old
// records upgrade themselves without anyone having to reset a password.
export function needsRehash(encoded) {
  const parameters = readArgonParameters(encoded);
  if (!parameters) return true;
  return !(
    parameters.m === ARGON_OPTIONS.memoryCost &&
    parameters.t === ARGON_OPTIONS.timeCost &&
    parameters.p === ARGON_OPTIONS.parallelism
  );
}

// Exposed only so tests can confirm the waiting-line limits.
export const PASSWORD_WORK_LIMITS = Object.freeze({
  MAX_CONCURRENT_HASHES,
  MAX_WAITING_HASHES,
  HASH_WAIT_TIMEOUT_MS,
});
